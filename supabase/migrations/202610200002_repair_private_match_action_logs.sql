-- Restore private game action history when the original 010 migration was not applied.
-- Run through Supabase CLI/db push or the Supabase SQL Editor for the live database.

CREATE TABLE IF NOT EXISTS public.private_match_action_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id uuid NOT NULL,
  turn_number integer,
  actor_user_id uuid,
  action_label text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS private_match_action_logs_room_created_idx
  ON public.private_match_action_logs(room_id, created_at DESC, id DESC);

ALTER TABLE public.private_match_action_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.private_match_action_logs FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.capture_private_match_action_log_v1()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $capture_private_match_action_log_v1$
DECLARE
  v_new jsonb := to_jsonb(NEW);
  v_old jsonb := to_jsonb(OLD);
  v_label text := nullif(trim(v_new ->> 'last_action_label'), '');
  v_turn_number integer;
BEGIN
  IF v_label IS NULL THEN
    RETURN NEW;
  END IF;

  IF (v_new ->> 'state_version') IS DISTINCT FROM (v_old ->> 'state_version')
     OR (v_new ->> 'last_action_label') IS DISTINCT FROM (v_old ->> 'last_action_label') THEN
    BEGIN
      v_turn_number := nullif(v_new ->> 'turn_number', '')::integer;
    EXCEPTION WHEN others THEN
      v_turn_number := NULL;
    END;

    INSERT INTO public.private_match_action_logs (
      room_id, turn_number, actor_user_id, action_label
    )
    VALUES (NEW.room_id, v_turn_number, auth.uid(), v_label);
  END IF;

  RETURN NEW;
END;
$capture_private_match_action_log_v1$;

DROP TRIGGER IF EXISTS private_match_action_log_capture ON public.room_match_states;
CREATE TRIGGER private_match_action_log_capture
  AFTER UPDATE ON public.room_match_states
  FOR EACH ROW
  EXECUTE FUNCTION public.capture_private_match_action_log_v1();

CREATE OR REPLACE FUNCTION public.get_private_match_action_log_v1(p_room_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $get_private_match_action_log_v1$
DECLARE
  v_user uuid := auth.uid();
  v_result jsonb;
BEGIN
  IF v_user IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.room_players
    WHERE room_id = p_room_id AND user_id = v_user
  ) THEN
    RAISE EXCEPTION '이 방의 참가자만 게임 행동 로그를 확인할 수 있습니다.';
  END IF;

  SELECT coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', entries.id,
        'room_id', entries.room_id,
        'turn_number', entries.turn_number,
        'actor_user_id', entries.actor_user_id,
        'actor_seat', entries.actor_seat,
        'actor_display_name', entries.actor_display_name,
        'action_label', entries.action_label,
        'created_at', entries.created_at
      )
      ORDER BY entries.created_at DESC, entries.id DESC
    ),
    '[]'::jsonb
  )
  INTO v_result
  FROM (
    SELECT
      l.id,
      l.room_id,
      l.turn_number,
      l.actor_user_id,
      l.action_label,
      l.created_at,
      rp.seat AS actor_seat,
      coalesce(
        nullif(trim(rp.temporary_nickname), ''),
        CASE
          WHEN rp.seat IS NOT NULL THEN '플레이어 ' || rp.seat::text
          ELSE '알 수 없는 플레이어'
        END
      ) AS actor_display_name
    FROM public.private_match_action_logs l
    LEFT JOIN public.room_players rp
      ON rp.room_id = l.room_id AND rp.user_id = l.actor_user_id
    WHERE l.room_id = p_room_id
  ) entries;

  RETURN coalesce(v_result, '[]'::jsonb);
END;
$get_private_match_action_log_v1$;

REVOKE ALL ON FUNCTION public.capture_private_match_action_log_v1() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.get_private_match_action_log_v1(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_private_match_action_log_v1(uuid) TO authenticated;
