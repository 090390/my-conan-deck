-- Make deck refresh an explicit player action instead of an automatic side effect.
-- The UI shows the "리프레시" button when the player's deck reaches zero.
-- This migration adds a transaction-safe RPC, records one timestamped action-log row,
-- and removes the auto-refresh logger introduced in migration 004.

CREATE TABLE IF NOT EXISTS public.private_match_action_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id uuid NOT NULL,
  turn_number integer,
  actor_user_id uuid,
  action_label text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS private_match_action_logs_room_created_idx
  ON public.private_match_action_logs(room_id, created_at DESC, id DESC);
ALTER TABLE public.private_match_action_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.private_match_action_logs FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS private_auto_deck_refresh_action_log ON public.room_player_game_states;
DROP FUNCTION IF EXISTS public.log_private_auto_deck_refresh_v1();

-- The existing server action may contain the empty-deck auto-refill branch in its PL/pgSQL body.
-- Patch only an empty-deck IF whose following block references the remove pile and deck refill.
DO $disable_existing_auto_refresh$
DECLARE
  v_signature text;
  v_definition text;
  v_original text;
  v_search text;
  v_after text;
  v_match text[];
  v_if_pos integer;
  v_search_pos integer;
  v_condition text;
  v_replacement text;
  v_patched_any boolean := false;
  v_scan_pos integer;
  v_candidate_count integer := 0;
BEGIN
  FOREACH v_signature IN ARRAY ARRAY[
    'public.perform_private_turn_action_v2(uuid,text,jsonb)',
    'public.perform_private_turn_action(uuid,text,jsonb)',
    'public.get_private_turn_state_v2(uuid)'
  ] LOOP
    IF to_regprocedure(v_signature) IS NULL THEN CONTINUE; END IF;

    SELECT pg_get_functiondef(to_regprocedure(v_signature)) INTO v_definition;
    v_definition := replace(v_definition, chr(13), '');
    v_original := v_definition;
    v_scan_pos := 1;

    LOOP
      v_search := substring(v_definition FROM v_scan_pos);
      v_match := regexp_match(
        v_search,
        '(?is)(if[[:space:]]+((?:(?!;).){0,180}deck_order(?:(?!;).){0,160}(?:=[[:space:]]*0|<=[[:space:]]*0)(?:(?!;).){0,60})[[:space:]]+then)'
      );
      EXIT WHEN v_match IS NULL;

      v_search_pos := position(v_match[1] IN v_search);
      EXIT WHEN v_search_pos <= 0;
      v_if_pos := v_scan_pos + v_search_pos - 1;
      v_after := substring(v_definition FROM v_if_pos + length(v_match[1]) FOR 2400);
      v_candidate_count := v_candidate_count + 1;

      IF v_after ~* '(remove_cards|remove_column|v_remove|리무브|remove area)'
         AND v_after ~* '(deck_order|random[[:space:]]*\(|shuffle|증거|evidence)' THEN
        v_condition := btrim(v_match[2]);
        v_replacement := 'IF false AND (' || v_condition || ') THEN';
        v_definition := overlay(
          v_definition PLACING v_replacement
          FROM v_if_pos FOR length(v_match[1])
        );
        v_patched_any := true;
        -- Continue scanning the remainder for a second automatic empty-deck branch.
        v_scan_pos := v_if_pos + length(v_replacement);
      ELSE
        v_scan_pos := v_if_pos + length(v_match[1]);
      END IF;

      EXIT WHEN v_scan_pos > length(v_definition);
    END LOOP;

    IF v_definition IS DISTINCT FROM v_original THEN
      EXECUTE v_definition;
    END IF;
  END LOOP;

  -- If refresh was implemented as a dedicated trigger rather than an inline RPC branch,
  -- remove that trigger only when its function clearly handles both deck refill and remove-pile shuffling.
  DECLARE
    v_trigger record;
  BEGIN
    FOR v_trigger IN
      SELECT t.tgname, p.prosrc
      FROM pg_trigger t
      JOIN pg_class c ON c.oid=t.tgrelid
      JOIN pg_namespace n ON n.oid=c.relnamespace
      JOIN pg_proc p ON p.oid=t.tgfoid
      WHERE n.nspname='public'
        AND c.relname='room_player_game_states'
        AND NOT t.tgisinternal
        AND t.tgname <> 'private_auto_deck_refresh_action_log'
        AND p.prosrc ~* 'deck_order'
        AND p.prosrc ~* '(remove_cards|remove_column|v_remove|리무브)'
        AND p.prosrc ~* '(random[[:space:]]*\(|shuffle|섞)'
    LOOP
      EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.room_player_game_states', v_trigger.tgname);
      v_patched_any := true;
    END LOOP;
  END;

  IF NOT v_patched_any THEN
    RAISE NOTICE 'No known automatic-refresh branch or trigger was found to disable. The manual refresh RPC is installed; verify the existing base RPC if the deck still refreshes automatically.';
  END IF;
END;
$disable_existing_auto_refresh$;

CREATE OR REPLACE FUNCTION public.refresh_private_deck_v1(p_room_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $refresh_private_deck_v1$
DECLARE
  v_user uuid := auth.uid();
  v_actor_seat integer;
  v_actor_name text;
  v_opponent_id uuid;
  v_turn_number integer;
  v_game public.room_player_game_states%ROWTYPE;
  v_opponent_game public.room_player_game_states%ROWTYPE;
  v_opponent_board public.room_player_turn_boards%ROWTYPE;
  v_remove_column text;
  v_remove_cards jsonb := '[]'::jsonb;
  v_shuffled_deck jsonb := '[]'::jsonb;
  v_opponent_deck jsonb := '[]'::jsonb;
  v_opponent_deck_new jsonb := '[]'::jsonb;
  v_evidence_card jsonb;
  v_clean_evidence_card jsonb;
  v_action_label text;
  v_has_action_log_trigger boolean := false;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION '로그인이 필요합니다.'; END IF;

  SELECT seat, coalesce(nullif(trim(temporary_nickname),''),'플레이어 '||seat::text)
    INTO v_actor_seat, v_actor_name
    FROM public.room_players
    WHERE room_id=p_room_id AND user_id=v_user;
  IF v_actor_seat IS NULL THEN RAISE EXCEPTION '이 방의 참가자만 리프레시할 수 있습니다.'; END IF;

  SELECT user_id INTO v_opponent_id
    FROM public.room_players
    WHERE room_id=p_room_id AND user_id<>v_user
    ORDER BY seat
    LIMIT 1;
  IF v_opponent_id IS NULL THEN RAISE EXCEPTION '상대 플레이어를 찾을 수 없습니다.'; END IF;

  SELECT * INTO v_game
    FROM public.room_player_game_states
    WHERE room_id=p_room_id AND user_id=v_user
    FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION '내 덱 상태를 찾을 수 없습니다.'; END IF;

  IF jsonb_array_length(coalesce(v_game.deck_order,'[]'::jsonb)) <> 0 THEN
    RAISE EXCEPTION '덱에 카드가 남아 있어 아직 리프레시할 수 없습니다.';
  END IF;

  SELECT column_name INTO v_remove_column
    FROM information_schema.columns
    WHERE table_schema='public'
      AND table_name='room_player_game_states'
      AND data_type='jsonb'
      AND column_name ILIKE '%remove%'
      AND column_name NOT ILIKE '%count%'
    ORDER BY CASE WHEN column_name='remove_cards' THEN 0 WHEN column_name ILIKE '%remove%cards%' THEN 1 ELSE 2 END, ordinal_position
    LIMIT 1;
  IF v_remove_column IS NULL THEN RAISE EXCEPTION '리무브 에이리어 카드 목록을 찾을 수 없습니다.'; END IF;

  EXECUTE format(
    'SELECT coalesce(%I,''[]''::jsonb) FROM public.room_player_game_states WHERE room_id=$1 AND user_id=$2 FOR UPDATE',
    v_remove_column
  ) INTO v_remove_cards USING p_room_id,v_user;

  IF jsonb_array_length(coalesce(v_remove_cards,'[]'::jsonb)) = 0 THEN
    RAISE EXCEPTION '리무브 에이리어에 카드가 없어 리프레시할 수 없습니다.';
  END IF;

  SELECT coalesce(jsonb_agg(e.value ORDER BY random()),'[]'::jsonb)
    INTO v_shuffled_deck
    FROM jsonb_array_elements(v_remove_cards) e(value);

  SELECT * INTO v_opponent_game
    FROM public.room_player_game_states
    WHERE room_id=p_room_id AND user_id=v_opponent_id
    FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION '상대의 덱 상태를 찾을 수 없습니다.'; END IF;

  SELECT * INTO v_opponent_board
    FROM public.room_player_turn_boards
    WHERE room_id=p_room_id AND user_id=v_opponent_id
    FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION '상대의 증거 에이리어 상태를 찾을 수 없습니다.'; END IF;

  v_opponent_deck := coalesce(v_opponent_game.deck_order,'[]'::jsonb);
  IF jsonb_array_length(v_opponent_deck) = 0 THEN
    RAISE EXCEPTION '상대 덱도 비어 있어 증거 카드를 추가할 수 없습니다. 상대가 먼저 리프레시해야 합니다.';
  END IF;

  -- Evidence is the opponent's top deck card, preserved as a hidden evidence card.
  SELECT e.value INTO v_evidence_card
    FROM jsonb_array_elements(v_opponent_deck) WITH ORDINALITY e(value,ordinality)
    ORDER BY e.ordinality
    LIMIT 1;
  SELECT coalesce(jsonb_agg(e.value ORDER BY e.ordinality)
      FILTER (WHERE e.ordinality > 1),'[]'::jsonb)
    INTO v_opponent_deck_new
    FROM jsonb_array_elements(v_opponent_deck) WITH ORDINALITY e(value,ordinality);

  v_clean_evidence_card := (
    v_evidence_card
      - 'rested' - 'status' - 'ap_bonus' - 'summoned_this_turn'
      - 'resolving' - 'host_instance_id' - 'set_owner_user_id'
  ) || jsonb_build_object('face_up',false);

  -- The transaction-local flag allows only this explicit RPC to refill the deck.
  PERFORM set_config('app.manual_deck_refresh','on',true);

  EXECUTE format(
    'UPDATE public.room_player_game_states SET deck_order=$3, %I=''[]''::jsonb, updated_at=now() WHERE room_id=$1 AND user_id=$2',
    v_remove_column
  ) USING p_room_id,v_user,v_shuffled_deck;

  UPDATE public.room_player_turn_boards
    SET remove_count=0,updated_at=now()
    WHERE room_id=p_room_id AND user_id=v_user;

  UPDATE public.room_player_game_states
    SET deck_order=v_opponent_deck_new,
        evidence_cards=coalesce(evidence_cards,'[]'::jsonb)||jsonb_build_array(v_clean_evidence_card),
        updated_at=now()
    WHERE room_id=p_room_id AND user_id=v_opponent_id;

  UPDATE public.room_player_turn_boards
    SET evidence_count=coalesce(evidence_count,0)+1,updated_at=now()
    WHERE room_id=p_room_id AND user_id=v_opponent_id;

  SELECT CASE
      WHEN coalesce(to_jsonb(m)->>'turn_number','') ~ '^[0-9]+$'
        THEN (to_jsonb(m)->>'turn_number')::integer
      ELSE NULL
    END
    INTO v_turn_number
    FROM public.room_match_states m
    WHERE room_id=p_room_id;
  v_action_label := format(
    '리프레시: %s가 리무브 에이리어의 %s장을 전체 셔플해 덱으로 되돌렸고, 상대에게 증거 1장을 추가했습니다.',
    v_actor_name,
    jsonb_array_length(v_remove_cards)
  );

  SELECT EXISTS (
    SELECT 1
    FROM pg_trigger t
    JOIN pg_class c ON c.oid=t.tgrelid
    JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relname='room_match_states'
      AND t.tgname='private_match_action_log_capture'
      AND NOT t.tgisinternal
      AND t.tgenabled <> 'D'
  ) INTO v_has_action_log_trigger;

  IF v_has_action_log_trigger THEN
    UPDATE public.room_match_states
      SET state_version=state_version+1,last_action_label=v_action_label
      WHERE room_id=p_room_id;
  ELSE
    INSERT INTO public.private_match_action_logs(room_id,turn_number,actor_user_id,action_label,created_at)
      VALUES (p_room_id,v_turn_number,v_user,v_action_label,now());
    UPDATE public.room_match_states
      SET state_version=state_version+1,last_action_label=v_action_label
      WHERE room_id=p_room_id;
  END IF;

  RETURN public.get_private_turn_state_v2(p_room_id);
END;
$refresh_private_deck_v1$;

REVOKE ALL ON FUNCTION public.refresh_private_deck_v1(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.refresh_private_deck_v1(uuid) TO authenticated;
